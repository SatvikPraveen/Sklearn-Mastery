def _oracle_counts(pred_a: ArrayLike, pred_b: ArrayLike, y_true: ArrayLike) -> Tuple[int, int, int, int]:
    """Return the (N11, N10, N01, N00) oracle-output contingency counts."""
    a = np.asarray(pred_a) == np.asarray(y_true)
    b = np.asarray(pred_b) == np.asarray(y_true)
    check_consistent_length(a, b)
    n11 = int(np.sum(a & b))
    n10 = int(np.sum(a & ~b))
    n01 = int(np.sum(~a & b))
    n00 = int(np.sum(~a & ~b))
    return n11, n10, n01, n00


def disagreement_measure(pred_a: ArrayLike, pred_b: ArrayLike) -> float:
    """Fraction of samples on which two predictors disagree (label-based, no oracle needed)."""
    a, b = np.asarray(pred_a), np.asarray(pred_b)
    check_consistent_length(a, b)
    return float(np.mean(a != b))


def q_statistic(pred_a: ArrayLike, pred_b: ArrayLike, y_true: ArrayLike) -> float:
    """Yule's Q-statistic between two predictors' correctness (``-1`` diverse, ``1`` identical).

    Returns ``0.0`` when the statistic is undefined.
    """
    n11, n10, n01, n00 = _oracle_counts(pred_a, pred_b, y_true)
    denom = n11 * n00 + n01 * n10
    return float((n11 * n00 - n01 * n10) / denom) if denom else 0.0


def correlation_coefficient(pred_a: ArrayLike, pred_b: ArrayLike, y_true: ArrayLike) -> float:
    """Phi correlation between the correctness indicators of two predictors."""
    n11, n10, n01, n00 = _oracle_counts(pred_a, pred_b, y_true)
    denom = np.sqrt(float((n11 + n10) * (n01 + n00) * (n11 + n01) * (n10 + n00)))
    return float((n11 * n00 - n01 * n10) / denom) if denom else 0.0


def double_fault_measure(pred_a: ArrayLike, pred_b: ArrayLike, y_true: ArrayLike) -> float:
    """Fraction of samples misclassified by *both* predictors (lower is more diverse)."""
    n11, n10, n01, n00 = _oracle_counts(pred_a, pred_b, y_true)
    total = n11 + n10 + n01 + n00
    return float(n00 / total) if total else 0.0


def agreement_rate(predictions: Sequence[ArrayLike]) -> float:
    """Fraction of samples on which every predictor in ``predictions`` agrees."""
    stacked = np.column_stack([np.asarray(p) for p in predictions])
    if stacked.shape[1] < 2:
        return 1.0
    return float(np.mean(np.all(stacked == stacked[:, [0]], axis=1)))


def kohavi_wolpert_variance(predictions: Sequence[ArrayLike], y_true: ArrayLike) -> float:
    """Kohavi-Wolpert variance of an ensemble (higher means more diverse)."""
    correct = np.column_stack([np.asarray(p) == np.asarray(y_true) for p in predictions]).astype(float)
    n_samples, n_models = correct.shape
    n_correct = correct.sum(axis=1)
    return float(np.sum(n_correct * (n_models - n_correct)) / (n_samples * n_models**2))


def entropy_measure(predictions: Sequence[ArrayLike], y_true: ArrayLike) -> float:
    """Kuncheva's entropy diversity measure in ``[0, 1]`` (``1`` = maximal disagreement)."""
    correct = np.column_stack([np.asarray(p) == np.asarray(y_true) for p in predictions]).astype(float)
    n_samples, n_models = correct.shape
    if n_models < 2:
        return 0.0
    n_correct = correct.sum(axis=1)
    scale = n_models - int(np.ceil(n_models / 2))
    return float(np.sum(np.minimum(n_correct, n_models - n_correct)) / (n_samples * scale))


def pairwise_diversity(pred_a: ArrayLike, pred_b: ArrayLike, y_true: ArrayLike) -> Dict[str, float]:
    """All pairwise diversity measures for two predictors.

    Args:
        pred_a: Predictions of the first model.
        pred_b: Predictions of the second model.
        y_true: Ground-truth labels.

    Returns:
        Dict with ``disagreement``, ``q_statistic``, ``correlation`` and ``double_fault``.
    """
    return {
        "disagreement": disagreement_measure(pred_a, pred_b),
        "q_statistic": q_statistic(pred_a, pred_b, y_true),
        "correlation": correlation_coefficient(pred_a, pred_b, y_true),
        "double_fault": double_fault_measure(pred_a, pred_b, y_true),
    }


def diversity_matrix(
    predictions: Sequence[ArrayLike], y_true: ArrayLike, measure: str = "disagreement"
) -> np.ndarray:
    """Symmetric ``(n_models, n_models)`` matrix of a pairwise diversity measure.

    Args:
        predictions: One prediction array per model.
        y_true: Ground-truth labels.
        measure: ``"disagreement"``, ``"q_statistic"``, ``"correlation"`` or ``"double_fault"``.

    Returns:
        Matrix whose diagonal is the measure of a model with itself.

    Raises:
        ValueError: For an unknown measure.
    """
    measures = {
        "disagreement": lambda a, b: disagreement_measure(a, b),
        "q_statistic": lambda a, b: q_statistic(a, b, y_true),
        "correlation": lambda a, b: correlation_coefficient(a, b, y_true),
        "double_fault": lambda a, b: double_fault_measure(a, b, y_true),
    }
    if measure not in measures:
        raise ValueError(f"measure must be one of {sorted(measures)}, got {measure!r}.")
    fn = measures[measure]
    n = len(predictions)
    matrix = np.zeros((n, n), dtype=float)
    for i in range(n):
        matrix[i, i] = fn(predictions[i], predictions[i])
        for j in range(i + 1, n):
            matrix[i, j] = matrix[j, i] = fn(predictions[i], predictions[j])
    return matrix


class EnsembleAnalyzer(LoggerMixin):
    """Quantify base-model diversity and the gain an ensemble obtains over its members.

    Args:
        task_type: ``"classification"`` (diversity measures are defined for
            labels) or ``"regression"`` (only prediction correlation and error
            statistics are reported).
    """

    PAIRWISE_MEASURES = ("disagreement", "q_statistic", "correlation", "double_fault")

    def __init__(self, task_type: str = CLASSIFICATION) -> None:
        if task_type not in (CLASSIFICATION, REGRESSION):
            raise ValueError(f"task_type must be 'classification' or 'regression', got {task_type!r}.")
        self.task_type = task_type

    @staticmethod
    def _normalise_models(models: Any) -> List[Tuple[str, Any]]:
        if isinstance(models, dict):
            return list(models.items())
        return _validate_estimators(models, "models")

    def get_predictions(self, models: Any, X: ArrayLike) -> Dict[str, np.ndarray]:
        """Predictions of already-fitted models as ``{name: predictions}``."""
        return {name: np.asarray(model.predict(X)) for name, model in self._normalise_models(models)}

    def calculate_diversity(
        self,
        models: Any,
        X: ArrayLike,
        y: ArrayLike,
        predictions: Optional[Dict[str, ArrayLike]] = None,
    ) -> Dict[str, Any]:
        """Compute pairwise and ensemble-level diversity statistics.

        Args:
            models: Fitted models as ``{name: model}`` or ``[(name, model), ...]``.
                Ignored when ``predictions`` is given.
            X: Feature matrix used to obtain predictions.
            y: Ground-truth targets.
            predictions: Optional pre-computed ``{name: predictions}`` to avoid re-predicting.

        Returns:
            Dict containing ``model_names``, ``individual_scores``, the mean of each pairwise
            measure (``disagreement``, ``q_statistics``, ``correlation``, ``double_fault``),
            the corresponding ``*_matrix`` entries, plus ``agreement_rate``,
            ``kohavi_wolpert_variance`` and ``entropy`` for classification.

        Raises:
            ValueError: If fewer than two models are provided.
        """
        preds = predictions if predictions is not None else self.get_predictions(models, X)
        names = list(preds.keys())
        if len(names) < 2:
            raise ValueError("Diversity analysis needs at least two models.")
        arrays = [np.asarray(preds[n]) for n in names]
        y = np.asarray(y)
        result: Dict[str, Any] = {"model_names": names}
        if self.task_type == CLASSIFICATION:
            result["individual_scores"] = {n: float(accuracy_score(y, p)) for n, p in zip(names, arrays)}
            upper = np.triu_indices(len(names), k=1)
            for measure in self.PAIRWISE_MEASURES:
                matrix = diversity_matrix(arrays, y, measure=measure)
                key = "q_statistics" if measure == "q_statistic" else measure
                result[key] = float(matrix[upper].mean())
                result[f"{measure}_matrix"] = matrix
            result["agreement_rate"] = agreement_rate(arrays)
            result["kohavi_wolpert_variance"] = kohavi_wolpert_variance(arrays, y)
            result["entropy"] = entropy_measure(arrays, y)
        else:
            stacked = np.column_stack(arrays).astype(float)
            result["individual_scores"] = {n: float(r2_score(y, p)) for n, p in zip(names, arrays)}
            corr = np.corrcoef(stacked, rowvar=False)
            corr = np.nan_to_num(np.atleast_2d(corr))
            upper = np.triu_indices(len(names), k=1)
            result["correlation"] = float(corr[upper].mean())
            result["correlation_matrix"] = corr
            errors = stacked - y.reshape(-1, 1)
            err_corr = np.nan_to_num(np.atleast_2d(np.corrcoef(errors, rowvar=False)))
            result["error_correlation"] = float(err_corr[upper].mean())
            result["error_correlation_matrix"] = err_corr
            result["prediction_spread"] = float(np.mean(np.std(stacked, axis=1)))
        self.logger.debug("Diversity computed for %d models", len(names))
        return result

    def analyze_ensemble(self, ensemble: Any, X: ArrayLike, y: ArrayLike) -> Dict[str, Any]:
        """Compare a fitted ensemble against its members.

        Args:
            ensemble: A fitted ensemble exposing ``predict`` and ``get_individual_predictions``.
            X: Feature matrix.
            y: Ground-truth targets.

        Returns:
            Dict with ``ensemble_score``, ``individual_scores``, ``best_individual_score``,
            ``ensemble_gain`` (ensemble minus best member) and the diversity statistics.

        Raises:
            AttributeError: If ``ensemble`` does not expose ``get_individual_predictions``.
        """
        if not hasattr(ensemble, "get_individual_predictions"):
            raise AttributeError("ensemble must implement get_individual_predictions(X).")
        members = ensemble.get_individual_predictions(X)
        names = self._member_names(ensemble, len(members))
        preds = dict(zip(names, (np.asarray(m) for m in members)))
        scorer = accuracy_score if self.task_type == CLASSIFICATION else r2_score
        ensemble_score = float(scorer(y, ensemble.predict(X)))
        individual = {n: float(scorer(y, p)) for n, p in preds.items()}
        best = max(individual.values())
        report: Dict[str, Any] = {
            "ensemble_score": ensemble_score,
            "individual_scores": individual,
            "best_individual_score": best,
            "ensemble_gain": ensemble_score - best,
        }
        if len(preds) >= 2:
            report["diversity"] = self.calculate_diversity(None, X, y, predictions=preds)
        return report

    @staticmethod
    def _member_names(ensemble: Any, n_members: int) -> List[str]:
        for attr in ("named_estimators_", "named_base_estimators_"):
            names = getattr(ensemble, attr, None)
            if names and len(names) == n_members:
                return list(names.keys())
        return [f"member_{i}" for i in range(n_members)]


