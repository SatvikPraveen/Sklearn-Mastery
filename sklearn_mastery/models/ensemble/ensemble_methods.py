# Stacking / blending
# --------------------------------------------------------------------------- #
class _StackedEnsembleBase(_BaseEnsemble):
    """Shared machinery for stacking and blending (meta-feature construction)."""

    base_estimators: EstimatorList
    meta_estimator: Optional[BaseEstimator]
    stack_method: str
    passthrough: bool
    n_jobs: Optional[int]

    def _tag_estimators(self) -> Sequence[Any]:
        return [est for _, est in (self.base_estimators or [])]

    def _resolve_stack_method(self, estimator: BaseEstimator, task: str) -> str:
        """Pick the prediction method used to build meta-features for ``estimator``."""
        method = self.stack_method
        if method == AUTO:
            if task == CLASSIFICATION and hasattr(estimator, "predict_proba"):
                return "predict_proba"
            if task == CLASSIFICATION and hasattr(estimator, "decision_function"):
                return "decision_function"
            return "predict"
        if method not in ("predict", "predict_proba", "decision_function"):
            raise ValueError(
                "stack_method must be 'auto', 'predict', 'predict_proba' or 'decision_function'."
            )
        if not hasattr(estimator, method):
            raise ValueError(f"{type(estimator).__name__} does not implement {method}().")
        return method

    def _default_meta_estimator(self, task: str) -> BaseEstimator:
        return LogisticRegression(max_iter=1000) if task == CLASSIFICATION else Ridge(alpha=1.0)

    def _as_meta_block(self, output: np.ndarray, method: str) -> np.ndarray:
        """Shape a base-estimator output into a 2-D meta-feature block."""
        output = np.asarray(output)
        if output.ndim == 1:
            if method == "predict" and self.task_type_ == CLASSIFICATION:
                output = self.le_.transform(output)  # class labels -> ordinal codes
            return output.reshape(-1, 1).astype(np.float64)
        if method == "predict_proba" and output.shape[1] == 2:
            return output[:, 1:2]  # binary: keep P(class 1) only
        return output.astype(np.float64)

    def _meta_features(self, X: Any, base_outputs: Sequence[np.ndarray]) -> Any:
        """Concatenate meta-feature blocks (plus raw features when ``passthrough``)."""
        blocks: List[Any] = [self._as_meta_block(out, m) for out, m in zip(base_outputs, self.stack_methods_)]
        if self.passthrough:
            blocks.append(X)
        return _hstack(blocks)

    def _base_outputs(self, X: Any) -> List[np.ndarray]:
        return [np.asarray(getattr(est, m)(X)) for est, m in zip(self.base_estimators_, self.stack_methods_)]

    def _finalise(self, X: Any, y: np.ndarray, meta_train: Any, y_meta: np.ndarray) -> None:
        """Fit the meta-estimator and record shared fitted attributes."""
        meta = (
            self.meta_estimator
            if self.meta_estimator is not None
            else self._default_meta_estimator(self.task_type_)
        )
        meta_task = _estimator_task_type(meta)
        if meta_task is not None and meta_task != self.task_type_:
            raise ValueError(
                f"meta_estimator is a {meta_task} estimator but the base estimators are {self.task_type_}."
            )
        self.meta_estimator_ = clone(meta).fit(meta_train, y_meta)
        self.named_base_estimators_ = dict(zip(self.base_names_, self.base_estimators_))
        if self.task_type_ == CLASSIFICATION:
            self.classes_ = self.le_.classes_
        self.n_features_in_ = X.shape[1]
        self.n_meta_features_in_ = meta_train.shape[1]

    # -- public API ---------------------------------------------------------- #
    def transform(self, X: ArrayLike) -> Any:
        """Meta-features produced by the fitted base estimators for ``X``."""
        check_is_fitted(self, "base_estimators_")
        X = _check_X(X)
        return self._meta_features(X, self._base_outputs(X))

    def get_base_predictions(self, X: ArrayLike) -> np.ndarray:
        """Point predictions of each base estimator.

        Args:
            X: Feature matrix.

        Returns:
            Array of shape ``(n_samples, n_base_estimators)``.
        """
        check_is_fitted(self, "base_estimators_")
        X = _check_X(X)
        return np.column_stack([np.asarray(est.predict(X)) for est in self.base_estimators_])

    def get_individual_predictions(self, X: ArrayLike) -> List[np.ndarray]:
        """Per-estimator predictions as a list (mirrors :meth:`VotingEnsemble.get_individual_predictions`)."""
        preds = self.get_base_predictions(X)
        return [preds[:, i] for i in range(preds.shape[1])]

    def get_feature_names_out(self, input_features: Optional[Sequence[str]] = None) -> np.ndarray:
        """Names of the meta-features returned by :meth:`transform`."""
        check_is_fitted(self, "base_estimators_")
        names: List[str] = []
        n_classes = len(getattr(self, "classes_", [])) if self.task_type_ == CLASSIFICATION else 0
        for name, method in zip(self.base_names_, self.stack_methods_):
            if method == "predict" or (method == "predict_proba" and n_classes == 2) or n_classes == 0:
                names.append(f"{name}_{method}" if method != "predict" else name)
            elif method == "predict_proba":
                names.extend(f"{name}_proba_{cls}" for cls in self.classes_)
            else:
                width = 1 if n_classes == 2 else n_classes
                names.extend(f"{name}_{method}_{i}" for i in range(width))
        if self.passthrough:
            if input_features is None:
                input_features = [f"x{i}" for i in range(self.n_features_in_)]
            names.extend(str(f) for f in input_features)
        return np.asarray(names, dtype=object)

    def predict(self, X: ArrayLike) -> np.ndarray:
        """Predict with the meta-estimator on the stacked meta-features."""
        check_is_fitted(self, "meta_estimator_")
        return np.asarray(self.meta_estimator_.predict(self.transform(X)))

    def predict_proba(self, X: ArrayLike) -> np.ndarray:
        """Meta-estimator class probabilities (classification only)."""
        check_is_fitted(self, "meta_estimator_")
        if not self.is_classification_:
            raise AttributeError("predict_proba is only available for classification ensembles.")
        return np.asarray(self.meta_estimator_.predict_proba(self.transform(X)))

    def decision_function(self, X: ArrayLike) -> np.ndarray:
        """Meta-estimator decision function (classification only)."""
        check_is_fitted(self, "meta_estimator_")
        if not self.is_classification_ or not hasattr(self.meta_estimator_, "decision_function"):
            raise AttributeError("decision_function is not available for this ensemble.")
        return np.asarray(self.meta_estimator_.decision_function(self.transform(X)))


class StackingEnsemble(_StackedEnsembleBase):
    """Stacked generalisation with cross-validated (out-of-fold) meta-features.

    Each base estimator is evaluated with ``cv``-fold cross-validation to obtain
    leak-free predictions for every training sample; the meta-estimator is then
    trained on these out-of-fold predictions. Finally the base estimators are
    refitted on the full training set for inference.

    Args:
        base_estimators: List of ``(name, estimator)`` pairs (level-0 models).
        meta_estimator: Level-1 model. Defaults to logistic regression / ridge.
        cv: Number of folds or a CV splitter. Integers use stratified folds for
            classification and are shuffled when ``random_state`` is given.
        stack_method: ``"auto"``, ``"predict"``, ``"predict_proba"`` or ``"decision_function"``.
            ``"auto"`` prefers probabilities for classifiers.
        passthrough: Append the original features to the meta-features.
        n_jobs: Parallel jobs for cross-validation and refitting.
        random_state: Seed used to shuffle the folds.
        task_type: ``"auto"`` (inferred from the estimators), ``"classification"`` or ``"regression"``.
        verbose: Log progress.

    Attributes:
        base_estimators_: Fitted level-0 estimators (refit on the full data).
        meta_estimator_: Fitted level-1 estimator.
        stack_methods_: Method used per base estimator.
        oof_meta_features_: Out-of-fold meta-feature matrix used to train the meta-estimator.
        classes_: Class labels (classification only).
    """

    def __init__(
        self,
        base_estimators: EstimatorList,
        meta_estimator: Optional[BaseEstimator] = None,
        cv: Any = 5,
        stack_method: str = AUTO,
        passthrough: bool = False,
        n_jobs: Optional[int] = None,
        random_state: Optional[int] = None,
        task_type: str = AUTO,
        verbose: bool = False,
    ) -> None:
        self.base_estimators = base_estimators
        self.meta_estimator = meta_estimator
        self.cv = cv
        self.stack_method = stack_method
        self.passthrough = passthrough
        self.n_jobs = n_jobs
        self.random_state = random_state
        self.task_type = task_type
        self.verbose = verbose

    def _build_cv(self, y: np.ndarray, task: str) -> Any:
        if isinstance(self.cv, (int, np.integer)):
            if self.cv < 2:
                raise ValueError(f"cv must be >= 2, got {self.cv}.")
            shuffle = self.random_state is not None
            splitter = StratifiedKFold if task == CLASSIFICATION else KFold
            return splitter(
                n_splits=int(self.cv), shuffle=shuffle, random_state=self.random_state if shuffle else None
            )
        return check_cv(self.cv, y, classifier=task == CLASSIFICATION)

    def fit(self, X: ArrayLike, y: ArrayLike) -> StackingEnsemble:
        """Fit base estimators (out-of-fold and on the full data) and the meta-estimator.

        Args:
            X: Feature matrix.
            y: Target vector.

        Returns:
            The fitted ensemble.

        Raises:
            ValueError: If the estimator list is invalid, tasks conflict, or ``cv`` is invalid.
        """
        estimators = _validate_estimators(self.base_estimators, "base_estimators")
        X, y = _check_X_y(X, y)
        self.task_type_ = _resolve_task_type(self.task_type, [est for _, est in estimators], y)
        self.base_names_ = [name for name, _ in estimators]
        self.stack_methods_ = [self._resolve_stack_method(est, self.task_type_) for _, est in estimators]
        if self.task_type_ == CLASSIFICATION:
            self.le_ = LabelEncoder().fit(y)
        self.cv_ = self._build_cv(y, self.task_type_)

        if self.verbose:
            self.logger.info("Generating out-of-fold predictions for %d base estimators", len(estimators))
        oof = Parallel(n_jobs=self.n_jobs)(
            delayed(cross_val_predict)(clone(est), X, y, cv=self.cv_, method=method)
            for (_, est), method in zip(estimators, self.stack_methods_)
        )
        self.base_estimators_ = list(
            Parallel(n_jobs=self.n_jobs)(delayed(_fit_one)(clone(est), X, y, None) for _, est in estimators)
        )
        self.oof_meta_features_ = self._meta_features(X, list(oof))
        self._finalise(X, y, self.oof_meta_features_, y)
        return self


class BlendingEnsemble(_StackedEnsembleBase):
    """Stacked generalisation with a single hold-out split ("blending").

    The training data is split once; base estimators are fitted on the first
    part and their predictions on the held-out part become the meta-features
    for the meta-estimator. Cheaper than :class:`StackingEnsemble` at the cost
    of using less data for each level.

    Args:
        base_estimators: List of ``(name, estimator)`` pairs.
        meta_estimator: Level-1 model. Defaults to logistic regression / ridge.
        holdout_size: Fraction (``0 < holdout_size < 1``) of training samples reserved
            for fitting the meta-estimator.
        stack_method: See :class:`StackingEnsemble`.
        passthrough: Append the original features to the meta-features.
        refit_base: Refit the base estimators on the *full* training set after the
            meta-estimator has been trained. Default keeps the canonical hold-out fit.
        n_jobs: Parallel jobs for fitting base estimators.
        random_state: Seed for the hold-out split (stratified for classification).
        task_type: ``"auto"``, ``"classification"`` or ``"regression"``.
        verbose: Log progress.

    Attributes:
        base_estimators_: Fitted base estimators.
        meta_estimator_: Fitted meta-estimator.
        train_indices_: Indices used to fit the base estimators.
        holdout_indices_: Indices used to fit the meta-estimator.
        holdout_meta_features_: Meta-feature matrix built on the hold-out part.
    """

    def __init__(
        self,
        base_estimators: EstimatorList,
        meta_estimator: Optional[BaseEstimator] = None,
        holdout_size: float = 0.2,
        stack_method: str = AUTO,
        passthrough: bool = False,
        refit_base: bool = False,
        n_jobs: Optional[int] = None,
        random_state: Optional[int] = None,
        task_type: str = AUTO,
        verbose: bool = False,
    ) -> None:
        self.base_estimators = base_estimators
        self.meta_estimator = meta_estimator
        self.holdout_size = holdout_size
        self.stack_method = stack_method
        self.passthrough = passthrough
        self.refit_base = refit_base
        self.n_jobs = n_jobs
        self.random_state = random_state
        self.task_type = task_type
        self.verbose = verbose

    def fit(self, X: ArrayLike, y: ArrayLike) -> BlendingEnsemble:
        """Fit base estimators on the training part and the meta-estimator on the hold-out part.

        Args:
            X: Feature matrix.
            y: Target vector.

        Returns:
            The fitted ensemble.

        Raises:
            ValueError: If ``holdout_size`` is outside ``(0, 1)`` or the estimator list is invalid.
        """
        if not 0.0 < float(self.holdout_size) < 1.0:
            raise ValueError(f"holdout_size must be in (0, 1), got {self.holdout_size}.")
        estimators = _validate_estimators(self.base_estimators, "base_estimators")
        X, y = _check_X_y(X, y)
        self.task_type_ = _resolve_task_type(self.task_type, [est for _, est in estimators], y)
        self.base_names_ = [name for name, _ in estimators]
        self.stack_methods_ = [self._resolve_stack_method(est, self.task_type_) for _, est in estimators]
        if self.task_type_ == CLASSIFICATION:
            self.le_ = LabelEncoder().fit(y)

        indices = np.arange(X.shape[0])
        stratify = y if self.task_type_ == CLASSIFICATION else None
        try:
            train_idx, hold_idx = train_test_split(
                indices, test_size=self.holdout_size, random_state=self.random_state, stratify=stratify
            )
        except ValueError:  # too few members of a class to stratify
            train_idx, hold_idx = train_test_split(
                indices, test_size=self.holdout_size, random_state=self.random_state
            )
        self.train_indices_, self.holdout_indices_ = train_idx, hold_idx
        X_train, y_train = X[train_idx], y[train_idx]
        X_hold, y_hold = X[hold_idx], y[hold_idx]

        if self.verbose:
            self.logger.info("Blending: %d train / %d hold-out samples", len(train_idx), len(hold_idx))
        self.base_estimators_ = list(
            Parallel(n_jobs=self.n_jobs)(
                delayed(_fit_one)(clone(est), X_train, y_train, None) for _, est in estimators
            )
        )
        self.holdout_meta_features_ = self._meta_features(X_hold, self._base_outputs(X_hold))
        self._finalise(X, y, self.holdout_meta_features_, y_hold)
        if self.refit_base:
            self.base_estimators_ = list(
                Parallel(n_jobs=self.n_jobs)(
                    delayed(_fit_one)(clone(est), X, y, None) for _, est in estimators
                )
            )
            self.named_base_estimators_ = dict(zip(self.base_names_, self.base_estimators_))
        return self


