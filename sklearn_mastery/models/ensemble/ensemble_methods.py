        bases = level_0_estimators if level_0_estimators is not None else base_estimators
        if bases is None:
            bases = self.default_classifiers() if task_type == CLASSIFICATION else self.default_regressors()
        meta = level_1_estimator if level_1_estimator is not None else final_estimator
        return StackingEnsemble(
            list(bases),
            meta_estimator=meta,
            cv=cv,
            stack_method=stack_method,
            passthrough=passthrough,
            n_jobs=n_jobs or self.n_jobs,
            random_state=self.random_state,
            task_type=task_type,
        )

