class BoostingEnsemble(_BaseEnsemble):
    """Unified wrapper over the boosting family.

    Args:
        algorithm: One of ``"adaboost"``, ``"gradientboosting"``, ``"histgradientboosting"``,
            ``"xgboost"`` or ``"lightgbm"``. The last two require the optional dependency.
        n_estimators: Number of boosting rounds.
        learning_rate: Shrinkage; ``None`` keeps the library default.
        max_depth: Depth of the weak learners; ``None`` keeps the library default
            (ignored by AdaBoost, whose depth is set through ``base_estimator``).
        base_estimator: Weak learner for AdaBoost (defaults to a depth-1 tree).
        task_type: ``"auto"`` (inferred from ``y``), ``"classification"`` or ``"regression"``.
        random_state: Seed forwarded to the underlying estimator.
        n_jobs: Parallel jobs (XGBoost / LightGBM only).
        estimator_params: Extra keyword arguments forwarded to the underlying estimator.
            Unsupported keys are dropped with a warning.
        verbose: Verbosity level for the underlying estimator.

    Attributes:
        estimator_: The fitted boosting estimator.
        classes_: Class labels (classification only).
        feature_importances_: Impurity-based importances when available.
        task_type_: Resolved task type.
    """

    def __init__(
        self,
        algorithm: str = "gradientboosting",
        n_estimators: int = 100,
        learning_rate: Optional[float] = None,
        max_depth: Optional[int] = None,
        base_estimator: Optional[BaseEstimator] = None,
        task_type: str = AUTO,
        random_state: Optional[int] = None,
        n_jobs: Optional[int] = None,
        estimator_params: Optional[Dict[str, Any]] = None,
        verbose: int = 0,
    ) -> None:
        self.algorithm = algorithm
        self.n_estimators = n_estimators
        self.learning_rate = learning_rate
        self.max_depth = max_depth
        self.base_estimator = base_estimator
        self.task_type = task_type
        self.random_state = random_state
        self.n_jobs = n_jobs
        self.estimator_params = estimator_params
        self.verbose = verbose

    # ------------------------------------------------------------------ #
    def _build_estimator(self, task: str) -> BaseEstimator:
        """Instantiate the underlying boosting estimator for ``task``."""
        algorithm = str(self.algorithm).lower().replace("_", "").replace("-", "")
        if algorithm not in BOOSTING_ALGORITHMS:
            raise ValueError(f"algorithm must be one of {BOOSTING_ALGORITHMS}, got {self.algorithm!r}.")
        if self.n_estimators < 1:
            raise ValueError(f"n_estimators must be >= 1, got {self.n_estimators}.")
        is_clf = task == CLASSIFICATION
        params: Dict[str, Any] = {"random_state": self.random_state}
        if self.learning_rate is not None:
            params["learning_rate"] = self.learning_rate

        if algorithm == "adaboost":
            cls: Any = AdaBoostClassifier if is_clf else AdaBoostRegressor
            weak = self.base_estimator
            if weak is None and self.max_depth is not None:
                weak = (
                    DecisionTreeClassifier(max_depth=self.max_depth)
                    if is_clf
                    else DecisionTreeRegressor(max_depth=self.max_depth)
                )
            params["n_estimators"] = self.n_estimators
            if weak is not None:
                params.update(_filter_kwargs(cls, {"estimator": clone(weak), "base_estimator": clone(weak)}))
        elif algorithm == "gradientboosting":
            cls = GradientBoostingClassifier if is_clf else GradientBoostingRegressor
            params.update(n_estimators=self.n_estimators, verbose=self.verbose)
            if self.max_depth is not None:
                params["max_depth"] = self.max_depth
        elif algorithm == "histgradientboosting":
            cls = HistGradientBoostingClassifier if is_clf else HistGradientBoostingRegressor
            params.update(max_iter=self.n_estimators, verbose=self.verbose)
            if self.max_depth is not None:
                params["max_depth"] = self.max_depth
        elif algorithm == "xgboost":
            if not HAS_XGBOOST:
                raise ImportError("algorithm='xgboost' requires the optional dependency 'xgboost'.")
            cls = xgb.XGBClassifier if is_clf else xgb.XGBRegressor
            params.update(n_estimators=self.n_estimators, n_jobs=self.n_jobs, verbosity=min(self.verbose, 3))
            if self.max_depth is not None:
                params["max_depth"] = self.max_depth
        else:  # lightgbm
            if not HAS_LIGHTGBM:
                raise ImportError("algorithm='lightgbm' requires the optional dependency 'lightgbm'.")
            cls = lgb.LGBMClassifier if is_clf else lgb.LGBMRegressor
            params.update(n_estimators=self.n_estimators, n_jobs=self.n_jobs, verbose=self.verbose or -1)
            if self.max_depth is not None:
                params["max_depth"] = self.max_depth

        params.update(_filter_kwargs(cls, dict(self.estimator_params or {})))
        return cls(**_filter_kwargs(cls, params))

    @property
    def _algorithm(self) -> str:
        return str(self.algorithm).lower().replace("_", "").replace("-", "")

    # ------------------------------------------------------------------ #
    def fit(self, X: ArrayLike, y: ArrayLike, sample_weight: Optional[ArrayLike] = None) -> BoostingEnsemble:
        """Fit the boosting model.

        Args:
            X: Feature matrix.
            y: Target vector. Class labels are label-encoded internally so string
                targets work with every backend.
            sample_weight: Optional sample weights.

        Returns:
            The fitted ensemble.

        Raises:
            ValueError: For an unknown ``algorithm`` or invalid ``n_estimators``.
            ImportError: If an optional backend is requested but not installed.
        """
        X, y = _check_X_y(X, y)
        self.task_type_ = _validate_task_type(self.task_type)
        if self.task_type_ == AUTO:
            self.task_type_ = _target_task_type(y)
        self.estimator_ = self._build_estimator(self.task_type_)
        y_fit: np.ndarray = y
        if self.task_type_ == CLASSIFICATION:
            self.le_ = LabelEncoder().fit(y)
            self.classes_ = self.le_.classes_
            y_fit = self.le_.transform(y)
        self.logger.debug("Fitting %s (%s)", type(self.estimator_).__name__, self.task_type_)
        _fit_one(self.estimator_, X, y_fit, None if sample_weight is None else column_or_1d(sample_weight))
        if hasattr(self.estimator_, "feature_importances_"):
            self.feature_importances_ = np.asarray(self.estimator_.feature_importances_, dtype=float)
        self.n_features_in_ = X.shape[1]
        return self

    def _decode(self, pred: np.ndarray) -> np.ndarray:
        if self.task_type_ == CLASSIFICATION:
            return self.le_.inverse_transform(np.asarray(pred).astype(int))
        return np.asarray(pred, dtype=np.float64)

    def predict(self, X: ArrayLike) -> np.ndarray:
        """Predict labels or values."""
        check_is_fitted(self, "estimator_")
        return self._decode(self.estimator_.predict(_check_X(X)))

    def predict_proba(self, X: ArrayLike) -> np.ndarray:
        """Class probabilities (classification only)."""
        check_is_fitted(self, "estimator_")
        if not self.is_classification_:
            raise AttributeError("predict_proba is only available for classification ensembles.")
        return np.asarray(self.estimator_.predict_proba(_check_X(X)))

    def staged_predict(self, X: ArrayLike) -> Iterator[np.ndarray]:
        """Yield predictions after each boosting round.

        Args:
            X: Feature matrix.

        Yields:
            Prediction array of shape ``(n_samples,)`` for rounds ``1 .. n_rounds``.
        """
        check_is_fitted(self, "estimator_")
        X = _check_X(X)
        est = self.estimator_
        if hasattr(est, "staged_predict"):
            for pred in est.staged_predict(X):
                yield self._decode(pred)
            return
        n_rounds = self.get_n_rounds()
        for i in range(1, n_rounds + 1):
            if self._algorithm == "xgboost":
                yield self._decode(est.predict(X, iteration_range=(0, i)))
            else:  # lightgbm
                yield self._decode(est.predict(X, num_iteration=i))

    def get_n_rounds(self) -> int:
        """Number of boosting rounds actually fitted (early stopping aware)."""
        check_is_fitted(self, "estimator_")
        est = self.estimator_
        for attr in ("n_estimators_", "n_iter_"):
            if hasattr(est, attr):
                return int(getattr(est, attr))
        if hasattr(est, "estimators_"):
            return len(est.estimators_)
        if hasattr(est, "get_booster"):  # xgboost
            return int(est.get_booster().num_boosted_rounds())
        if hasattr(est, "booster_"):  # lightgbm
            return int(est.booster_.current_iteration())
        return int(self.n_estimators)

    def get_feature_importance(self) -> np.ndarray:
        """Impurity/gain-based feature importances of the fitted model.

        Returns:
            Non-negative array of length ``n_features_in_``.

        Raises:
            AttributeError: If the backend does not expose ``feature_importances_``
                (e.g. histogram gradient boosting; use permutation importance instead).
        """
        check_is_fitted(self, "estimator_")
        if not hasattr(self, "feature_importances_"):
            raise AttributeError(
                f"{type(self.estimator_).__name__} does not expose feature_importances_; "
                "use sklearn.inspection.permutation_importance instead."
            )
        return self.feature_importances_


