def _check_X(X: ArrayLike, *, allow_nan: bool = True) -> Any:
    """Validate a feature matrix, tolerating NaN when the base learners allow it.

    Args:
        X: Feature matrix (dense or sparse).
        allow_nan: Whether NaN values are permitted.

    Returns:
        Validated 2-D array or sparse matrix.
    """
    finite: Union[bool, str] = "allow-nan" if allow_nan else True
    try:
        return check_array(X, dtype=None, accept_sparse=["csr", "csc"], ensure_all_finite=finite)
    except TypeError:  # pragma: no cover - scikit-learn < 1.6 keyword name
        return check_array(X, dtype=None, accept_sparse=["csr", "csc"], force_all_finite=finite)


def _check_X_y(X: ArrayLike, y: ArrayLike) -> Tuple[Any, np.ndarray]:
    """Validate ``X`` and ``y`` jointly."""
    X = _check_X(X)
    y = column_or_1d(y, warn=True)
    check_consistent_length(X, y)
    return X, y


def _target_task_type(y: ArrayLike) -> str:
    """Infer the learning task from the target vector.

    Args:
        y: Target vector.

    Returns:
        ``"classification"`` or ``"regression"``.

    Raises:
        ValueError: If the target type is not supported.
    """
    target = type_of_target(y)
    if target in ("binary", "multiclass"):
        return CLASSIFICATION
    if target == "continuous":
        return REGRESSION
    raise ValueError(f"Unsupported target type '{target}'; expected binary, multiclass or continuous.")


def _estimator_task_type(estimator: Any) -> Optional[str]:
    """Return the task type implied by an estimator, or ``None`` if unknown."""
    if estimator is None:
        return None
    if is_classifier(estimator):
        return CLASSIFICATION
    if is_regressor(estimator):
        return REGRESSION
    return None


def _validate_task_type(task_type: str) -> str:
    """Validate a ``task_type`` argument."""
    if task_type not in _TASK_TYPES:
        raise ValueError(f"task_type must be one of {_TASK_TYPES}, got {task_type!r}.")
    return task_type


def _validate_estimators(estimators: Any, argument: str = "estimators") -> List[Tuple[str, BaseEstimator]]:
    """Validate a list of ``(name, estimator)`` pairs.

    Args:
        estimators: Candidate list.
        argument: Name of the argument (used in error messages).

    Returns:
        The validated list.

    Raises:
        ValueError: If the list is empty, malformed, or names are not unique.
    """
    if estimators is None or len(estimators) == 0:
        raise ValueError(
            f"'{argument}' must contain at least one (name, estimator) pair; got {estimators!r}."
        )
    validated: List[Tuple[str, BaseEstimator]] = []
    names: List[str] = []
    for item in estimators:
        if not isinstance(item, (tuple, list)) or len(item) != 2:
            raise ValueError(f"Each element of '{argument}' must be a (name, estimator) tuple; got {item!r}.")
        name, estimator = item
        if not isinstance(name, str) or not name:
            raise ValueError(f"Estimator names must be non-empty strings; got {name!r}.")
        if estimator is None or not hasattr(estimator, "fit"):
            raise ValueError(f"Estimator '{name}' does not implement fit().")
        if "__" in name:
            raise ValueError(f"Estimator names must not contain '__'; got {name!r}.")
        names.append(name)
        validated.append((name, estimator))
    if len(set(names)) != len(names):
        raise ValueError(f"Estimator names must be unique; got {names}.")
    return validated


def _resolve_task_type(
    task_type: str,
    estimators: Sequence[Any],
    y: Optional[ArrayLike] = None,
) -> str:
    """Resolve ``task_type='auto'`` from the base estimators and/or the target.

    Args:
        task_type: Requested task type (``"auto"``, ``"classification"`` or ``"regression"``).
        estimators: Base estimators (used for inference and validation).
        y: Optional target used when the estimators are inconclusive.

    Returns:
        The resolved task type.

    Raises:
        ValueError: If the base estimators disagree with each other or with ``task_type``.
    """
    _validate_task_type(task_type)
    implied = {t for t in (_estimator_task_type(est) for est in estimators) if t is not None}
    if len(implied) > 1:
        raise ValueError(
            "Base estimators mix classifiers and regressors; all estimators must solve the same task. "
            f"Found: {[(type(est).__name__, _estimator_task_type(est)) for est in estimators]}"
        )
    if task_type != AUTO:
        if implied and task_type not in implied:
            raise ValueError(f"task_type={task_type!r} but base estimators are {implied.pop()} estimators.")
        return task_type
    if implied:
        return implied.pop()
    if y is not None:
        return _target_task_type(y)
    raise ValueError("Could not infer task type; pass task_type='classification' or 'regression'.")


def _fit_one(
    estimator: BaseEstimator, X: Any, y: np.ndarray, sample_weight: Optional[np.ndarray]
) -> BaseEstimator:
    """Fit a single (already cloned) estimator, forwarding ``sample_weight`` when supported."""
    if sample_weight is not None and has_fit_parameter(estimator, "sample_weight"):
        return estimator.fit(X, y, sample_weight=sample_weight)
    return estimator.fit(X, y)


def _filter_kwargs(estimator_cls: Any, kwargs: Dict[str, Any]) -> Dict[str, Any]:
    """Drop keyword arguments that ``estimator_cls`` does not accept (logging each drop)."""
    try:
        params = inspect.signature(estimator_cls.__init__).parameters
    except (TypeError, ValueError):  # pragma: no cover - C-implemented signatures
        return dict(kwargs)
    if any(p.kind is inspect.Parameter.VAR_KEYWORD for p in params.values()):
        return dict(kwargs)
    accepted: Dict[str, Any] = {}
    for key, value in kwargs.items():
        if key in params:
            accepted[key] = value
        else:
            logger.warning("Dropping unsupported parameter %r for %s.", key, estimator_cls.__name__)
    return accepted


def _hstack(blocks: Sequence[Any]) -> Any:
    """Horizontally stack dense and/or sparse blocks."""
    if any(sparse.issparse(b) for b in blocks):
        return sparse.hstack([sparse.csr_matrix(b) for b in blocks]).tocsr()
    return np.hstack([np.asarray(b) for b in blocks])


# --------------------------------------------------------------------------- #
# Base class
# --------------------------------------------------------------------------- #
class _BaseEnsemble(BaseEstimator, LoggerMixin):
    """Common scaffolding for the ensemble wrappers (tags, scoring, persistence)."""

    task_type: str

    # -- task-type aware scikit-learn tags ---------------------------------- #
    def _tags_task_type(self) -> Optional[str]:
        """Task type used for estimator tags; ``None`` when it cannot be determined."""
        fitted = getattr(self, "task_type_", None)
        if fitted is not None:
            return fitted
        declared = getattr(self, "task_type", AUTO)
        if declared in (CLASSIFICATION, REGRESSION):
            return declared
        try:
            return _resolve_task_type(AUTO, self._tag_estimators())
        except ValueError:
            return None

    def _tag_estimators(self) -> Sequence[Any]:
        """Estimators inspected to infer the task type before fitting."""
        return []

    @property
    def _estimator_type(self) -> Optional[str]:  # scikit-learn < 1.6
        task = self._tags_task_type()
        if task == CLASSIFICATION:
            return "classifier"
        if task == REGRESSION:
            return "regressor"
        return None

    def __sklearn_tags__(self):  # scikit-learn >= 1.6
        tags = super().__sklearn_tags__()
        task = self._tags_task_type()
        if HAS_SKLEARN_TAGS and task == CLASSIFICATION:
            tags.estimator_type = "classifier"
            tags.classifier_tags = ClassifierTags()
        elif HAS_SKLEARN_TAGS and task == REGRESSION:
            tags.estimator_type = "regressor"
            tags.regressor_tags = RegressorTags()
        return tags

    # -- generic API -------------------------------------------------------- #
    @property
    def is_classification_(self) -> bool:
        """Whether the fitted ensemble solves a classification task."""
        check_is_fitted(self, "task_type_")
        return self.task_type_ == CLASSIFICATION

    def score(self, X: ArrayLike, y: ArrayLike) -> float:
        """Accuracy (classification) or R^2 (regression) on ``(X, y)``.

        Args:
            X: Feature matrix.
            y: Ground-truth targets.

        Returns:
            The score.
        """
        y_pred = self.predict(X)
        if self.is_classification_:
            return float(accuracy_score(y, y_pred))
        return float(r2_score(y, y_pred))

    def save_model(self, filepath: Union[str, Path]) -> Path:
        """Persist the fitted ensemble with :mod:`joblib`.

        Args:
            filepath: Destination path (parent directories are created).

        Returns:
            The resolved path written to.

        Raises:
            sklearn.exceptions.NotFittedError: If the ensemble is not fitted.
        """
        check_is_fitted(self, "task_type_")
        path = Path(filepath)
        path.parent.mkdir(parents=True, exist_ok=True)
        joblib.dump(self, path)
        self.logger.info("Saved %s to %s", type(self).__name__, path)
        return path

    def load_model(self, filepath: Union[str, Path]) -> _BaseEnsemble:
        """Restore a persisted ensemble *into this instance*.

        Args:
            filepath: Path produced by :meth:`save_model`.

        Returns:
            ``self`` with parameters and fitted state replaced by the stored ones.

        Raises:
            FileNotFoundError: If ``filepath`` does not exist.
            TypeError: If the stored object is not an instance of this class.
        """
        path = Path(filepath)
        if not path.exists():
            raise FileNotFoundError(f"No saved model at {path}")
        loaded = joblib.load(path)
        if not isinstance(loaded, type(self)):
            raise TypeError(f"Expected a {type(self).__name__} in {path}, found {type(loaded).__name__}.")
        self.__dict__.clear()
        self.__dict__.update(loaded.__dict__)
        self.logger.info("Loaded %s from %s", type(self).__name__, path)
        return self

    @classmethod
    def load(cls, filepath: Union[str, Path]) -> _BaseEnsemble:
        """Load a persisted ensemble as a new instance."""
        instance = cls.__new__(cls)
        return instance.load_model(filepath)


# --------------------------------------------------------------------------- #
# Voting
# --------------------------------------------------------------------------- #
class VotingEnsemble(_BaseEnsemble):
    """Majority-vote / probability-averaging ensemble of heterogeneous estimators.

    For classification, ``voting="hard"`` performs (weighted) majority voting on
    predicted labels and ``voting="soft"`` averages predicted probabilities. For
    regression both settings average the predictions.

    Args:
        estimators: List of ``(name, estimator)`` pairs. All must be classifiers
            or all regressors.
        voting: ``"hard"`` or ``"soft"``.
        weights: Optional per-estimator weights (same length as ``estimators``).
        n_jobs: Number of parallel jobs for fitting the base estimators.
        task_type: ``"auto"`` (inferred from the estimators), ``"classification"``
            or ``"regression"``.
        verbose: Log per-estimator fitting progress.

    Attributes:
        estimators_: Fitted clones of the base estimators.
        named_estimators_: Mapping from name to fitted estimator.
        classes_: Class labels (classification only).
        task_type_: Resolved task type.
        n_features_in_: Number of input features.

    Example:
        >>> ensemble = VotingEnsemble([("rf", RandomForestClassifier()), ("lr", LogisticRegression())],
        ...                           voting="soft")
        >>> ensemble.fit(X_train, y_train).predict(X_test)
    """

    def __init__(
        self,
        estimators: EstimatorList,
        voting: str = "hard",
        weights: Optional[Sequence[float]] = None,
        n_jobs: Optional[int] = None,
        task_type: str = AUTO,
        verbose: bool = False,
    ) -> None:
        self.estimators = estimators
        self.voting = voting
        self.weights = weights
        self.n_jobs = n_jobs
        self.task_type = task_type
        self.verbose = verbose

    def _tag_estimators(self) -> Sequence[Any]:
        return [est for _, est in (self.estimators or [])]

    # ------------------------------------------------------------------ #
    def fit(self, X: ArrayLike, y: ArrayLike, sample_weight: Optional[ArrayLike] = None) -> VotingEnsemble:
        """Fit every base estimator on ``(X, y)``.

        Args:
            X: Feature matrix of shape ``(n_samples, n_features)``.
            y: Target vector.
            sample_weight: Optional sample weights forwarded to estimators that support them.

        Returns:
            The fitted ensemble.

        Raises:
            ValueError: If ``estimators`` is empty, mixes classifiers and regressors,
                ``voting`` is invalid, or soft voting is requested for estimators
                without ``predict_proba``.
        """
        if self.voting not in ("hard", "soft"):
            raise ValueError(f"voting must be 'hard' or 'soft', got {self.voting!r}.")
        estimators = _validate_estimators(self.estimators)
        X, y = _check_X_y(X, y)
        self.task_type_ = _resolve_task_type(self.task_type, [est for _, est in estimators], y)
        if self.task_type_ == CLASSIFICATION:
            if not all(is_classifier(est) for _, est in estimators):
                raise ValueError("All estimators must be classifiers for a classification VotingEnsemble.")
            if self.voting == "soft":
                missing = [name for name, est in estimators if not hasattr(est, "predict_proba")]
                if missing:
                    raise ValueError(f"Soft voting requires predict_proba; missing for {missing}.")
        elif not all(is_regressor(est) for _, est in estimators):
            raise ValueError("All estimators must be regressors for a regression VotingEnsemble.")

        weights = self._weights(len(estimators))
        if sample_weight is not None:
            sample_weight = column_or_1d(sample_weight)
            check_consistent_length(X, sample_weight)

        if self.task_type_ == CLASSIFICATION:
            self.le_ = LabelEncoder().fit(y)
            self.classes_ = self.le_.classes_

        if self.verbose:
            self.logger.info("Fitting %d estimators (%s voting)", len(estimators), self.voting)
        fitted = Parallel(n_jobs=self.n_jobs)(
            delayed(_fit_one)(clone(est), X, y, sample_weight) for _, est in estimators
        )
        self.estimators_ = list(fitted)
        self.named_estimators_ = {name: est for (name, _), est in zip(estimators, self.estimators_)}
        self.weights_ = weights
        self.n_features_in_ = X.shape[1]
        return self

    def _weights(self, n_estimators: int) -> np.ndarray:
        if self.weights is None:
            return np.ones(n_estimators, dtype=float)
        weights = np.asarray(self.weights, dtype=float)
        if weights.shape != (n_estimators,):
            raise ValueError(f"weights must have length {n_estimators}, got shape {weights.shape}.")
        if np.any(weights < 0) or not np.any(weights > 0):
            raise ValueError("weights must be non-negative with at least one positive entry.")
        return weights

    # ------------------------------------------------------------------ #
    def get_individual_predictions(self, X: ArrayLike) -> List[np.ndarray]:
        """Predictions of every fitted base estimator.

        Args:
            X: Feature matrix.

        Returns:
            List (in ``estimators`` order) of prediction arrays of shape ``(n_samples,)``.
        """
        check_is_fitted(self, "estimators_")
        X = _check_X(X)
        return [np.asarray(est.predict(X)) for est in self.estimators_]

    def get_individual_probabilities(self, X: ArrayLike) -> List[np.ndarray]:
        """Class probabilities of every fitted base estimator (classification only)."""
        check_is_fitted(self, "estimators_")
        if not self.is_classification_:
            raise AttributeError("Probabilities are only available for classification ensembles.")
        X = _check_X(X)
        return [np.asarray(est.predict_proba(X)) for est in self.estimators_]

    def transform(self, X: ArrayLike) -> np.ndarray:
        """Stack the individual predictions into an ``(n_samples, n_estimators)`` matrix."""
        return np.column_stack(self.get_individual_predictions(X))

    def predict_proba(self, X: ArrayLike) -> np.ndarray:
        """Weighted average of the base estimators' class probabilities.

        Args:
            X: Feature matrix.

        Returns:
            Array of shape ``(n_samples, n_classes)`` whose rows sum to one.

        Raises:
            AttributeError: For regression ensembles or when a base estimator lacks ``predict_proba``.
        """
        probas = self.get_individual_probabilities(X)
        return np.average(np.stack(probas, axis=0), axis=0, weights=self.weights_)

    def predict(self, X: ArrayLike) -> np.ndarray:
        """Aggregate the base predictions according to ``voting``.

        Args:
            X: Feature matrix.

        Returns:
            Predicted labels (classification) or values (regression).
        """
        check_is_fitted(self, "estimators_")
        if not self.is_classification_:
            preds = np.column_stack(self.get_individual_predictions(X)).astype(np.float64)
            return np.average(preds, axis=1, weights=self.weights_)
        if self.voting == "soft":
            return self.classes_[np.argmax(self.predict_proba(X), axis=1)]
        encoded = [self.le_.transform(p) for p in self.get_individual_predictions(X)]
        n_samples = len(encoded[0])
        votes = np.zeros((n_samples, len(self.classes_)), dtype=float)
        rows = np.arange(n_samples)
        for weight, pred in zip(self.weights_, encoded):
            votes[rows, pred] += weight
        return self.le_.inverse_transform(np.argmax(votes, axis=1))

    def agreement_rate(self, X: ArrayLike) -> float:
        """Fraction of samples on which *all* base estimators produce the same prediction."""
        return agreement_rate(self.get_individual_predictions(X))


