class BaggingEnsemble(_BaseEnsemble):
    """Bootstrap-aggregating ensemble of a single base learner.

    Thin, task-aware wrapper around :class:`sklearn.ensemble.BaggingClassifier`
    / :class:`sklearn.ensemble.BaggingRegressor` that adds out-of-bag score
    access and per-member predictions.

    Args:
        base_estimator: Estimator to replicate. Defaults to a decision tree of the
            appropriate kind.
        n_estimators: Number of bootstrap replicas.
        max_samples: Fraction (float) or count (int) of samples drawn per replica.
        max_features: Fraction (float) or count (int) of features drawn per replica.
        bootstrap: Draw samples with replacement.
        bootstrap_features: Draw features with replacement.
        oob_score: Compute the out-of-bag generalisation estimate.
        n_jobs: Parallel jobs for fitting/predicting.
        random_state: Seed controlling the bootstrap draws.
        task_type: ``"auto"`` (inferred from ``base_estimator`` or ``y``), ``"classification"``
            or ``"regression"``.
        verbose: Verbosity forwarded to the scikit-learn bagging estimator.

    Attributes:
        ensemble_: The fitted scikit-learn bagging estimator.
        estimators_: Fitted replicas.
        estimators_features_: Feature indices used by each replica.
        oob_score_: Out-of-bag score (when ``oob_score=True``).
        classes_: Class labels (classification only).
        task_type_: Resolved task type.
    """

    def __init__(
        self,
        base_estimator: Optional[BaseEstimator] = None,
        n_estimators: int = 10,
        max_samples: Union[int, float] = 1.0,
        max_features: Union[int, float] = 1.0,
        bootstrap: bool = True,
        bootstrap_features: bool = False,
        oob_score: bool = False,
        n_jobs: Optional[int] = None,
        random_state: Optional[int] = None,
        task_type: str = AUTO,
        verbose: int = 0,
    ) -> None:
        self.base_estimator = base_estimator
        self.n_estimators = n_estimators
        self.max_samples = max_samples
        self.max_features = max_features
        self.bootstrap = bootstrap
        self.bootstrap_features = bootstrap_features
        self.oob_score = oob_score
        self.n_jobs = n_jobs
        self.random_state = random_state
        self.task_type = task_type
        self.verbose = verbose

    def _tag_estimators(self) -> Sequence[Any]:
        return [self.base_estimator] if self.base_estimator is not None else []

    def fit(self, X: ArrayLike, y: ArrayLike, sample_weight: Optional[ArrayLike] = None) -> BaggingEnsemble:
        """Fit the bagging ensemble.

        Args:
            X: Feature matrix.
            y: Target vector.
            sample_weight: Optional sample weights.

        Returns:
            The fitted ensemble.

        Raises:
            ValueError: If ``n_estimators`` is not positive or the base estimator's task
                conflicts with ``task_type``.
        """
        if self.n_estimators < 1:
            raise ValueError(f"n_estimators must be >= 1, got {self.n_estimators}.")
        X, y = _check_X_y(X, y)
        self.task_type_ = _resolve_task_type(self.task_type, self._tag_estimators(), y)
        if self.base_estimator is None:
            base = (
                DecisionTreeClassifier(random_state=self.random_state)
                if self.task_type_ == CLASSIFICATION
                else DecisionTreeRegressor(random_state=self.random_state)
            )
        else:
            base = clone(self.base_estimator)
        bagging_cls = BaggingClassifier if self.task_type_ == CLASSIFICATION else BaggingRegressor
        params = dict(
            n_estimators=self.n_estimators,
            max_samples=self.max_samples,
            max_features=self.max_features,
            bootstrap=self.bootstrap,
            bootstrap_features=self.bootstrap_features,
            oob_score=self.oob_score,
            n_jobs=self.n_jobs,
            random_state=self.random_state,
            verbose=self.verbose,
        )
        params.update(_filter_kwargs(bagging_cls, {"estimator": base, "base_estimator": base}))
        self.ensemble_ = bagging_cls(**params)
        self.logger.debug("Fitting %s with %d estimators", bagging_cls.__name__, self.n_estimators)
        _fit_one(self.ensemble_, X, y, None if sample_weight is None else column_or_1d(sample_weight))
        self.base_estimator_ = base
        self.estimators_ = self.ensemble_.estimators_
        self.estimators_features_ = self.ensemble_.estimators_features_
        if self.task_type_ == CLASSIFICATION:
            self.classes_ = self.ensemble_.classes_
        if self.oob_score:
            self.oob_score_ = float(self.ensemble_.oob_score_)
        self.n_features_in_ = X.shape[1]
        return self

    def predict(self, X: ArrayLike) -> np.ndarray:
        """Aggregate predictions of all bootstrap replicas."""
        check_is_fitted(self, "ensemble_")
        return self.ensemble_.predict(_check_X(X))

    def predict_proba(self, X: ArrayLike) -> np.ndarray:
        """Averaged class probabilities (classification only)."""
        check_is_fitted(self, "ensemble_")
        if not self.is_classification_:
            raise AttributeError("predict_proba is only available for classification ensembles.")
        return self.ensemble_.predict_proba(_check_X(X))

    def get_oob_score(self) -> float:
        """Out-of-bag score computed during :meth:`fit`.

        Returns:
            OOB accuracy (classification) or R^2 (regression).

        Raises:
            ValueError: If the ensemble was built with ``oob_score=False``.
        """
        check_is_fitted(self, "ensemble_")
        if not self.oob_score:
            raise ValueError("Out-of-bag score is only available when oob_score=True.")
        return self.oob_score_

    def get_individual_predictions(self, X: ArrayLike) -> List[np.ndarray]:
        """Predictions of every bootstrap replica (on its own feature subset)."""
        check_is_fitted(self, "ensemble_")
        X = _check_X(X)
        preds: List[np.ndarray] = []
        for est, features in zip(self.estimators_, self.estimators_features_):
            pred = np.asarray(est.predict(X[:, features]))
            if self.task_type_ == CLASSIFICATION:
                pred = self.classes_[pred.astype(int)]
            preds.append(pred)
        return preds

    def get_feature_importance(self) -> np.ndarray:
        """Average ``feature_importances_`` over replicas that expose it.

        Returns:
            Importance vector of length ``n_features_in_`` (zero for never-sampled features).

        Raises:
            AttributeError: If the base estimator does not expose ``feature_importances_``.
        """
        check_is_fitted(self, "ensemble_")
        if not hasattr(self.estimators_[0], "feature_importances_"):
            raise AttributeError(f"{type(self.estimators_[0]).__name__} has no feature_importances_.")
        importance = np.zeros(self.n_features_in_, dtype=float)
        for est, features in zip(self.estimators_, self.estimators_features_):
            importance[features] += est.feature_importances_
        total = importance.sum()
        return importance / total if total > 0 else importance


