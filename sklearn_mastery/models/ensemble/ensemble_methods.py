"""Ensemble learning wrappers and diversity analysis utilities.

This module provides scikit-learn compatible meta-estimators that combine
several base learners:

* :class:`VotingEnsemble` -- hard/soft majority voting (classification) or
  weighted averaging (regression) over a list of ``(name, estimator)`` pairs.
* :class:`BaggingEnsemble` -- bootstrap aggregation of a single base learner
  with sample/feature subsampling and out-of-bag scoring.
* :class:`BoostingEnsemble` -- unified wrapper around AdaBoost, gradient
  boosting, histogram gradient boosting and (optionally) XGBoost / LightGBM.
* :class:`StackingEnsemble` -- stacked generalisation with out-of-fold
  meta-features generated by cross-validation.
* :class:`BlendingEnsemble` -- stacked generalisation with meta-features
  generated on a single hold-out split.

All wrappers follow the scikit-learn estimator contract: constructor
arguments are stored verbatim (so :func:`sklearn.base.clone` works), ``fit``
returns ``self`` and fitted attributes end with an underscore.  Every wrapper
can be persisted with :meth:`save_model` and restored with :meth:`load_model`.

:class:`EnsembleMethods` is a convenience factory used throughout the
examples, and the module-level diversity measures (Q-statistic, disagreement,
double-fault, Kohavi-Wolpert variance, ...) together with
:class:`EnsembleAnalyzer` support quantitative analysis of *why* an ensemble
helps.

Optional dependencies (``xgboost``, ``lightgbm``) are guarded by the
``HAS_XGBOOST`` and ``HAS_LIGHTGBM`` flags; the module imports without them.
"""

