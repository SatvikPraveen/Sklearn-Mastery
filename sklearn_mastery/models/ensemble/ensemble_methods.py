    def get_multi_level_stacking(
        self,
        level_0_estimators: EstimatorList,
        level_1_estimators: EstimatorList,
        level_2_estimator: Optional[BaseEstimator] = None,
        cv_folds: Sequence[int] = (5, 3),
        stack_methods: Sequence[str] = (AUTO, AUTO),
        task_type: str = CLASSIFICATION,
    ) -> StackingEnsemble:
        """Two-level stacking: each level-1 estimator stacks the level-0 pool, level-2 stacks those.

        Args:
            level_0_estimators: ``(name, estimator)`` pairs forming the base pool.
            level_1_estimators: ``(name, estimator)`` pairs, each used as the meta-learner of an
                independent :class:`StackingEnsemble` over the level-0 pool.
            level_2_estimator: Final meta-learner over the level-1 stacks.
            cv_folds: Folds used at level 0 and level 1 respectively.
            stack_methods: ``stack_method`` used at each level.
            task_type: ``"classification"`` or ``"regression"``.

        Returns:
            The (unfitted) nested :class:`StackingEnsemble`.
        """
        if len(cv_folds) != 2 or len(stack_methods) != 2:
            raise ValueError("cv_folds and stack_methods must each have exactly two entries.")
        level_0 = _validate_estimators(level_0_estimators, "level_0_estimators")
        level_1 = _validate_estimators(level_1_estimators, "level_1_estimators")
        inner = [
            (
                name,
                StackingEnsemble(
                    level_0,
                    meta_estimator=meta,
                    cv=cv_folds[0],
                    stack_method=stack_methods[0],
                    n_jobs=self.n_jobs,
                    random_state=self.random_state,
                    task_type=task_type,
                ),
            )
            for name, meta in level_1
        ]
        return StackingEnsemble(
            inner,
            meta_estimator=level_2_estimator,
            cv=cv_folds[1],
            stack_method=stack_methods[1],
            n_jobs=self.n_jobs,
            random_state=self.random_state,
            task_type=task_type,
        )

